#!/bin/bash

# Reverts install.sh and removes the plugin: the tunnel, the generated profiles, the drop-in, the polkit rule,
# the fortivpn link, the openfortivpn package and finally this folder. ~/.config/openfortivpn-profiles.conf
# stays: it is user data.

set -euo pipefail

PLUGIN_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PLUGIN_ID=sergey-frv.openfortivpn
PLUGINS_DIR="$HOME/.config/omarchy/plugins"
CONF_DIR=/etc/openfortivpn
MARKER="# Generated by sergey-frv.openfortivpn install.sh"
LEGACY_MARKER="# Generated by ~/supplement/install-openfortivpn.sh"
CLI="$HOME/.local/bin/fortivpn"
DROPIN_DIR=/etc/systemd/system/openfortivpn@.service.d

if [[ -x $PLUGIN_DIR/bin/fortivpn ]]; then
  "$PLUGIN_DIR/bin/fortivpn" down || {
    echo "uninstall.sh: fortivpn down failed; stop the tunnel and rerun" >&2
    exit 1
  }
else
  sudo systemctl stop 'openfortivpn@*.service'
fi

shopt -s nullglob
for f in "$CONF_DIR"/*.conf; do
  first="$(head -n 1 "$f" 2>/dev/null || true)"
  if [[ $first == "$MARKER" || $first == "$LEGACY_MARKER" ]]; then
    sudo rm -f "$f"
    echo "Removed $f"
  fi
done
shopt -u nullglob

sudo rm -f "$DROPIN_DIR/saml.conf"
if [[ -d $DROPIN_DIR ]]; then
  sudo rmdir --ignore-fail-on-non-empty "$DROPIN_DIR"
fi
# rules.d is not readable by the user: the rule is removed without a check
sudo rm -f /etc/polkit-1/rules.d/50-openfortivpn.rules
sudo systemctl daemon-reload
sudo systemctl reset-failed 'openfortivpn@*' || true

if [[ -L $CLI ]]; then
  rm -f "$CLI"
  echo "Removed $CLI"
fi

omarchy pkg drop openfortivpn

# Last, since it removes the folder this script runs from; bash keeps reading the open file.
# omarchy plugin remove asks the running shell; without it only the folder is removed.
if [[ -e $PLUGINS_DIR/$PLUGIN_ID ]]; then
  if ! omarchy plugin remove "$PLUGIN_ID" --yes; then
    rm -rf "${PLUGINS_DIR:?}/$PLUGIN_ID"
    echo "Removed $PLUGINS_DIR/$PLUGIN_ID; the shell drops it on its next start"
  fi
fi

echo "Removed. The profiles stay in ${XDG_CONFIG_HOME:-$HOME/.config}/openfortivpn-profiles.conf"
