#!/bin/bash

# System part of the plugin: openfortivpn with SAML login as the systemd service openfortivpn@<profile>, the
# fortivpn CLI and the bar widget. Run it from the plugin folder that `omarchy plugin add` created
# (~/.config/omarchy/plugins/sergey-frv.openfortivpn); uninstall.sh reverts it and keeps the profile file.
#
# Profiles come from ~/.config/openfortivpn-profiles.conf, one per line: name | host:port[/realm] |
# Every profile becomes /etc/openfortivpn/<name>.conf. The drop-in adds --saml-login to the packaged
# openfortivpn@.service, the polkit rule lets members of wheel start and stop it without sudo. A rerun applies
# the profile file again.

set -euo pipefail

PLUGIN_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PLUGIN_ID=sergey-frv.openfortivpn
PLUGINS_DIR="$HOME/.config/omarchy/plugins"
PROFILES_FILE="${XDG_CONFIG_HOME:-$HOME/.config}/openfortivpn-profiles.conf"
CONF_DIR=/etc/openfortivpn
MARKER="# Generated by sergey-frv.openfortivpn install.sh"
# Files generated before the plugin had its own repository carry this marker; they are ours as well
LEGACY_MARKER="# Generated by ~/supplement/install-openfortivpn.sh"
CLI="$HOME/.local/bin/fortivpn"

fail() {
  echo "install.sh: $*" >&2
  exit 1
}
warn() { echo "install.sh: $*" >&2; }

trim() {
  local s=$1
  s="${s#"${s%%[![:space:]]*}"}"
  printf '%s' "${s%"${s##*[![:space:]]}"}"
}

generated() {
  local first
  first="$(head -n 1 "$1" 2>/dev/null || true)"
  [[ $first == "$MARKER" || $first == "$LEGACY_MARKER" ]]
}

# The CLI link and the widget both point at this folder: from anywhere else the shell would not load it
[[ $PLUGIN_DIR == "$PLUGINS_DIR/$PLUGIN_ID" ]] ||
  fail "run the copy in $PLUGINS_DIR/$PLUGIN_ID; add the plugin first: omarchy plugin add <repository url>"
for f in bin/fortivpn system/saml.conf system/50-openfortivpn.rules manifest.json; do
  [[ -e $PLUGIN_DIR/$f ]] || fail "$PLUGIN_DIR/$f not found"
done

omarchy pkg add openfortivpn

# Profiles are read before anything is changed: an invalid line stops the install
names=() hosts=() ports=() realms=()
declare -A seen=()
if [[ -f $PROFILES_FILE ]]; then
  lineno=0
  while IFS= read -r line || [[ -n $line ]]; do
    lineno=$((lineno + 1))
    [[ $line =~ ^[[:space:]]*(#|$) ]] && continue
    IFS='|' read -r name target extra <<<"$line"
    name=$(trim "$name")
    target=$(trim "${target:-}")
    extra=$(trim "${extra:-}")
    where="$PROFILES_FILE:$lineno"

    [[ $name =~ ^[A-Za-z0-9_-]+$ ]] || fail "$where: profile name '$name' must match ^[A-Za-z0-9_-]+\$"
    [[ -z ${seen[$name]:-} ]] || fail "$where: profile '$name' is defined twice"
    seen[$name]=1

    host_port="${target%%/*}"
    realm=""
    if [[ $target == */* ]]; then
      realm="${target#*/}"
      [[ $realm =~ ^[^[:space:]/]+$ ]] || fail "$where: invalid realm '$realm'"
    fi
    host="${host_port%%:*}"
    port=""
    if [[ $host_port == *:* ]]; then
      port="${host_port#*:}"
      [[ $port =~ ^[0-9]+$ ]] || fail "$where: invalid port '$port'"
    fi
    [[ $host =~ ^[A-Za-z0-9.-]+$ ]] || fail "$where: invalid host '$host'"
    [[ -z $extra ]] || warn "$where: extra arguments '$extra' are ignored; the service takes only host, port and realm"

    names+=("$name") hosts+=("$host") ports+=("$port") realms+=("$realm")
  done <"$PROFILES_FILE"
else
  warn "$PROFILES_FILE not found: no profiles are generated, existing ones are kept"
  warn "format: name | host:port[/realm] |"
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# /etc/openfortivpn/<name>.conf per profile; a file without the marker is not ours and stays untouched
for i in "${!names[@]}"; do
  name=${names[i]}
  dest="$CONF_DIR/$name.conf"
  {
    echo "$MARKER"
    echo "# Profile '$name' of ~/.config/openfortivpn-profiles.conf: edit that file and rerun install.sh"
    echo "host = ${hosts[i]}"
    if [[ -n ${ports[i]} ]]; then echo "port = ${ports[i]}"; fi
    if [[ -n ${realms[i]} ]]; then echo "realm = ${realms[i]}"; fi
  } >"$tmp/$name.conf"

  if [[ -e $dest ]] && ! generated "$dest"; then
    warn "$dest was not generated by this script: left as is, profile '$name' uses it"
  elif ! cmp -s "$tmp/$name.conf" "$dest"; then
    sudo install -D -m 644 -o root -g root "$tmp/$name.conf" "$dest"
    echo "Wrote $dest"
  fi
done

# Generated files of profiles gone from the profile file; /etc/openfortivpn/config has no .conf suffix
shopt -s nullglob
for f in "$CONF_DIR"/*.conf; do
  name=$(basename "$f" .conf)
  [[ -z ${seen[$name]:-} ]] || continue
  if generated "$f"; then
    sudo rm -f "$f"
    echo "Removed $f"
  fi
done
shopt -u nullglob

sudo install -D -m 644 "$PLUGIN_DIR/system/saml.conf" /etc/systemd/system/openfortivpn@.service.d/saml.conf
sudo install -D -m 644 "$PLUGIN_DIR/system/50-openfortivpn.rules" /etc/polkit-1/rules.d/50-openfortivpn.rules
sudo systemctl daemon-reload

# A file in place of the link is moved aside, the way Omarchy backs up configs
mkdir -p "$(dirname "$CLI")"
if [[ -e $CLI && ! -L $CLI ]]; then
  mv "$CLI" "$CLI.bak.$(date +%s)"
  echo "Moved $CLI to $CLI.bak.*"
fi
ln -sfn "$PLUGIN_DIR/bin/fortivpn" "$CLI"

# The widget goes to the right section on the first install; a rerun keeps the place the user gave it.
# The shell discovers a new plugin only on a rescan; the wait for it repeats omarchy-plugin-add.
enable_hint="after login run: omarchy-shell shell rescanPlugins && omarchy plugin enable $PLUGIN_ID right"
if omarchy-shell shell ping >/dev/null 2>&1; then
  omarchy-shell shell rescanPlugins >/dev/null
  enabled=""
  for ((attempt = 0; attempt < 40; attempt++)); do
    enabled=$(omarchy-plugin-list --json | jq -r --arg id "$PLUGIN_ID" '.[] | select(.id == $id) | .enabled') ||
      enabled=""
    [[ -z $enabled ]] || break
    sleep 0.05
  done
  case $enabled in
  true) echo "$PLUGIN_ID is already enabled" ;;
  false) omarchy plugin enable "$PLUGIN_ID" right || warn "the widget is not enabled; $enable_hint" ;;
  *) warn "omarchy-shell does not see $PLUGIN_ID; check: omarchy plugin validate $PLUGIN_DIR" ;;
  esac
else
  warn "omarchy-shell is not running; $enable_hint"
fi

echo "Profiles: ${names[*]:-none}. Check: fortivpn status"
